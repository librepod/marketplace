#!/bin/sh
# One-time (idempotent) OpenBao bootstrap: init, KV v2 engine, Kubernetes
# auth, policies, roles. Runs in the bootstrap Job alongside the
# store-credentials container; they exchange state through /shared. Policies
# are site-specific: every *.hcl mounted at /policies (openbao-policies
# ConfigMap from the overlay) becomes an OpenBao policy named after the
# file. (The audit device is declared in the server config — see
# helmrelease.yaml.)
#
# Deliberately NO OIDC/SSO auth method: configuring one would make this
# bootstrap depend on the IdP chain (the step-ca CA as
# oidc_discovery_ca_pem + the casdoor-sso-controller output) and order
# openbao behind step-issuer -> casdoor. openbao is a system app and stays
# independent of all of that; login is token-based (README "Login").
set -e

SA_DIR=/var/run/secrets/kubernetes.io/serviceaccount

# Wall-clock budget for every wait below. The Job's activeDeadlineSeconds
# (900) is a TERMINAL failure — DeadlineExceeded is never retried by the
# job controller, and a pod hung in a wait loop burns the whole budget and
# wedges the bootstrap until someone deletes the Job by hand. Dying at our
# own earlier deadline instead is an ordinary pod failure: restartPolicy
# Never + backoffLimit re-run the whole Job, each attempt with a fresh 900s.
# 780s leaves room for the config calls after the last wait. Sized for a
# slow-link cold boot (openbao image pull + PVC mount can lag the Job pod
# by minutes); if even that is not enough, the backoff retries absorb it.
# (The env override shrinks the budget in tests; the ConfigMap carries
# substitute: disabled, so ${...:-} is safe from postBuild substitution.)
BUDGET=$(( $(date +%s) + ${OPENBAO_BOOTSTRAP_BUDGET_SECONDS:-780} ))
budget_left() { [ "$(date +%s)" -lt "$BUDGET" ]; }
budget_out() {
  echo "ERROR: budget expired before the openbao API became usable; exiting so the Job backoff retries with a fresh deadline." >&2
  exit 1
}

# restartPolicy Never does NOT kill sibling containers when one exits: with
# this container dead, store-credentials would wait on /shared/done until
# its own budget expires. Signal the exit so the store container terminates
# within its 2s poll and the pod fails (and retries) immediately.
trap 'touch /shared/bootstrap-exited' EXIT

# Wait until the status API answers, and capture the parsed value (the
# table prints "Initialized true|false" in every state, sealed included).
echo "waiting for the openbao API..."
until [ -n "$INITIALIZED" ]; do
  INITIALIZED="$(bao status 2>&1 | sed -n 's/^Initialized[[:space:]]*//p')"
  sleep 3
  budget_left || budget_out
done

# Acquire a root token: reuse the one stored by a previous run if present,
# otherwise perform the one-time initialization. Unbounded in wall-clock
# terms only up to the shared budget; covers sidecar image-pull lag on a
# slow link (store-credentials may start minutes after this container).
until [ -f /shared/root-token ] || [ -f /shared/no-secret ]; do
  sleep 1
  budget_left || budget_out
done

# Cross-check the credentials handshake against actual server state: a
# mismatch means the data PVC or the credentials Secret was wiped behind
# the other's back, and neither can be regenerated by re-running this Job.
if [ -f /shared/root-token ]; then
  if [ "$INITIALIZED" != "true" ]; then
    # Credentials were restored (or a stale Secret survived) but the data
    # volume is empty: drop the seal-volume copy too, or the restore branch
    # would resurrect this dead token on every future run.
    rm -f /seal/credentials.json
    echo "ERROR: credentials exist but the server is not initialized (data PVC wiped?); removed the stale seal-volume credentials copy. Delete the openbao-credentials Secret and this Job, then re-apply for a fresh init." >&2
    exit 1
  fi
  # Already initialized: wait for auto-unseal (static seal) before
  # re-applying the configuration below.
  until bao status 2>&1 | grep -q "^Sealed[[:space:]]*false"; do
    sleep 3
    budget_left || budget_out
  done
  BAO_TOKEN="$(cat /shared/root-token)"
elif [ -f /shared/no-secret ]; then
  if [ "$INITIALIZED" = "true" ]; then
    echo "ERROR: server is already initialized (data PVC survived) but no credentials could be found — both the openbao-credentials Secret and the seal-volume copy are gone, so the root token and recovery keys are unrecoverable. Wipe the data PVC (README 'Operational notes') and delete this Job." >&2
    exit 1
  fi
  echo "initializing openbao..."
  # A seal is configured, so no secret_shares/threshold (Shamir params) —
  # init returns recovery keys + root token. Init overrides the Job-wide
  # BAO_CLIENT_TIMEOUT per call: a client-side timeout on an init that
  # committed server-side (slow NFS-backed writes) drops the ONLY copy of
  # the credentials and lands the retry in the unrecoverable branch at the
  # top of this file. 5m still dies inside the wall-clock budget's retry.
  INIT_JSON="$(BAO_CLIENT_TIMEOUT=5m bao operator init -format=json)"
  printf '%s' "$INIT_JSON" > /shared/credentials.json
  touch /shared/done
  BAO_TOKEN="$(printf '%s' "$INIT_JSON" | sed -n 's/.*"root_token"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
else
  echo "ERROR: timed out waiting for credentials handshake" >&2
  exit 1
fi
export BAO_TOKEN

# KV v2 secrets engine at apps/
if ! bao secrets list -format=json | grep -q '"apps/"'; then
  bao secrets enable -path=apps kv-v2
fi

# KV v2 secrets engine at system/ — infrastructure/DR secrets that regular
# apps must not see (eso-read-apps grants read on apps/* only). Currently
# holds the step-ca CA backup (system/step-ca).
if ! bao secrets list -format=json | grep -q '"system/"'; then
  bao secrets enable -path=system kv-v2
fi

# Kubernetes auth method. No token_reviewer_jwt: the chart binds the server
# ServiceAccount to system:auth-delegator, so OpenBao reviews client tokens
# with its own auto-rotating SA token.
if ! bao auth list -format=json | grep -q '"kubernetes/"'; then
  bao auth enable kubernetes
fi
bao write auth/kubernetes/config \
  kubernetes_host="https://kubernetes.default.svc:443" \
  kubernetes_ca_cert=@"$SA_DIR/ca.crt"

# Policies: every mounted *.hcl becomes a policy named after its file.
for hcl in /policies/*.hcl; do
  [ -f "$hcl" ] || continue   # no policies ConfigMap (optional mount)
  bao policy write "$(basename "$hcl" .hcl)" "$hcl"
done

# Roles. ttl=20m holds only for the consumer shapes provisioned below:
# one-shot Jobs/initContainers that log in and use the token immediately
# (every retry loop re-logins per attempt), and daemons that re-authenticate
# on expiry (marketplace-ui's client tracks lease_duration and re-logins on
# 403; ESO re-auths on lease expiry). A NEW long-lived consumer that caches
# a single login will start getting 403s exactly 20 minutes after it boots
# — with nothing else failing. Give such a consumer expiry handling or a
# periodic token (token_period); don't just raise the TTL.
bao write auth/kubernetes/role/external-secrets \
  bound_service_account_names=openbao-eso \
  bound_service_account_namespaces=openbao \
  policies=eso-read-apps ttl=20m

# marketplace-ui: app settings under apps/ (marketplace-ui-write-apps) and
# first-run onboarding state under system/ (marketplace-ui-system — the
# onboarding record and the admin password).
bao write auth/kubernetes/role/marketplace-ui \
  bound_service_account_names=marketplace-ui \
  bound_service_account_namespaces=marketplace-ui \
  policies=marketplace-ui-write-apps,marketplace-ui-system ttl=20m

# CA producer: the step-certificates bootstrap Job logs in with this role to
# push the public root + intermediate CA into KV apps/step-ca (policy
# step-certificates-write-apps) and the full CA backup — keys, config,
# passwords — into KV system/step-ca (policy step-ca-backup). Producer-push:
# this bootstrap never reads from the step-ca namespace.
bao write auth/kubernetes/role/step-certificates \
  bound_service_account_names=step-ca-bootstrap-step-issuer \
  bound_service_account_namespaces=step-ca \
  policies=step-certificates-write-apps,step-ca-backup ttl=20m

# CA restore: the step-certificates Deployment (SA step-ca-restore) logs in
# with this role to restore the CA from the system/step-ca backup when its
# PVC turns up empty (policy step-ca-restore, read-only).
bao write auth/kubernetes/role/step-ca-restore \
  bound_service_account_names=step-ca-restore \
  bound_service_account_namespaces=step-ca \
  policies=step-ca-restore ttl=20m

# Credential producer: the gogs publish-auth Job logs in with this role to
# push the committed flux-account credential into KV apps/user-apps-source
# (write-only on that one path — policy gogs-write-apps). Consumers
# (flux-system, marketplace-ui) sync it via ExternalSecret. Producer-push:
# this bootstrap never reads from the gogs namespace.
bao write auth/kubernetes/role/gogs \
  bound_service_account_names=gogs-publish-source-auth \
  bound_service_account_namespaces=gogs \
  policies=gogs-write-apps ttl=20m

# NOTE (post-SSO migration): this script provisions but never removes auth
# methods, so clusters bootstrapped while the OIDC/SSO auth method existed
# keep auth/oidc and its admin-sso role (policies admin,default) enabled.
# Disable once by hand on those clusters: bao auth disable oidc

# The audit device is declared in the server configuration (see
# helmrelease.yaml), not enabled via the API.

echo "openbao bootstrap complete"
